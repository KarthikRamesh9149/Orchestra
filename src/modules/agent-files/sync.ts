import { createHash } from "node:crypto";

export const GENERATED_ZONE_BEGIN = "<!-- ORCHESTRA BEGIN generated -->";
export const GENERATED_ZONE_END = "<!-- ORCHESTRA END generated -->";
export const MANUAL_ZONE_BEGIN = "<!-- ORCHESTRA BEGIN manual-notes -->";
export const MANUAL_ZONE_END = "<!-- ORCHESTRA END manual-notes -->";

export type AgentFileConflictType =
  | "missing_markers"
  | "generated_zone_modified"
  | "manual_zone_parse_failed"
  | "local_file_deleted"
  | "local_hash_mismatch"
  | "unsupported_file_path"
  | "unknown";

export type ParsedAgentFileZones = {
  markerStatus: "valid" | "missing_markers" | "manual_zone_parse_failed";
  generatedZone: string | null;
  manualZone: string | null;
  generatedZoneHash: string | null;
  manualZoneHash: string | null;
};

export function wrapGeneratedMarkdown(generatedMarkdown: string, manualNotes = defaultManualNotes()) {
  return [
    GENERATED_ZONE_BEGIN,
    generatedMarkdown.trim(),
    GENERATED_ZONE_END,
    "",
    MANUAL_ZONE_BEGIN,
    manualNotes.trim(),
    MANUAL_ZONE_END
  ].join("\n");
}

export function parseAgentFileZones(content: string): ParsedAgentFileZones {
  const generated = extractZone(content, GENERATED_ZONE_BEGIN, GENERATED_ZONE_END);
  const manual = extractZone(content, MANUAL_ZONE_BEGIN, MANUAL_ZONE_END);
  if (!generated.found && !manual.found) {
    return {
      markerStatus: "missing_markers",
      generatedZone: null,
      manualZone: null,
      generatedZoneHash: null,
      manualZoneHash: null
    };
  }
  if (!generated.valid || !manual.valid) {
    return {
      markerStatus: "manual_zone_parse_failed",
      generatedZone: generated.content,
      manualZone: manual.content,
      generatedZoneHash: generated.content ? sha256(generated.content) : null,
      manualZoneHash: manual.content ? sha256(manual.content) : null
    };
  }
  return {
    markerStatus: "valid",
    generatedZone: generated.content,
    manualZone: manual.content,
    generatedZoneHash: generated.content ? sha256(generated.content) : null,
    manualZoneHash: manual.content ? sha256(manual.content) : null
  };
}

export function preserveManualZone(previousContent: string | null | undefined, nextGeneratedMarkdown: string) {
  if (!previousContent) return { content: wrapGeneratedMarkdown(nextGeneratedMarkdown), conflict: null as AgentFileConflictType | null };
  const previous = parseAgentFileZones(previousContent);
  if (previous.markerStatus === "missing_markers") {
    return { content: wrapGeneratedMarkdown(nextGeneratedMarkdown), conflict: null as AgentFileConflictType | null };
  }
  if (previous.markerStatus !== "valid") {
    return { content: previousContent, conflict: previous.markerStatus as AgentFileConflictType };
  }
  return {
    content: wrapGeneratedMarkdown(nextGeneratedMarkdown, previous.manualZone ?? defaultManualNotes()),
    conflict: null as AgentFileConflictType | null
  };
}

export function diffSummary(oldContent: string | null | undefined, newContent: string) {
  const oldLines = splitLines(oldContent ?? "");
  const newLines = splitLines(newContent);
  let changedLines = 0;
  const max = Math.max(oldLines.length, newLines.length);
  for (let index = 0; index < max; index += 1) {
    if ((oldLines[index] ?? "") !== (newLines[index] ?? "")) changedLines += 1;
  }
  return {
    oldHash: oldContent ? sha256(oldContent) : null,
    newHash: sha256(newContent),
    oldLineCount: oldLines.length,
    newLineCount: newLines.length,
    changedLineCount: changedLines
  };
}

