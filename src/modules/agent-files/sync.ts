export function sha256(value: string) {
  return createHash("sha256").update(value).digest("hex");
}

function extractZone(content: string, begin: string, end: string) {
  const start = content.indexOf(begin);
  const finish = content.indexOf(end);
  if (start === -1 && finish === -1) return { found: false, valid: false, content: null as string | null };
  if (start === -1 || finish === -1 || finish <= start) return { found: true, valid: false, content: null as string | null };
  return {
    found: true,
    valid: true,
    content: content.slice(start + begin.length, finish).trim()
  };
}

function splitLines(value: string) {
  return value.length ? value.split(/\r?\n/) : [];
}

function defaultManualNotes() {
  return "<!-- Add local notes here. Orchestra preserves this zone during local sync. -->";
}

function listLines(values: unknown[]) {
  const lines = values.map((value) => String(value ?? "").trim()).filter(Boolean);
  return lines.length ? lines.map((line) => `- ${line}`) : ["- None recorded."];
}
